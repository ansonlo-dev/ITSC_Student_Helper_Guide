# Mainland convention uses “ ” rather than the 「 」 used in TW/HK.
QUOTES = {"「": "“", "」": "”", "『": "‘", "』": "’"}


def convert(text: str) -> str:
    text = cc.convert(text)
    for src, dst in TERMS:
        text = text.replace(src, dst)
    for src, dst in QUOTES.items():
        text = text.replace(src, dst)
    return text.replace("/zh-TW/", "/zh-CN/")


count = 0
for src_path in sorted(SRC.rglob("*.md")):
    dst_path = DST / src_path.relative_to(SRC)
    dst_path.parent.mkdir(parents=True, exist_ok=True)
    dst_path.write_text(convert(src_path.read_text(encoding="utf-8")), encoding="utf-8")
    count += 1
    print(f"  {src_path} -> {dst_path}")
print(f"\n{count} files converted")
